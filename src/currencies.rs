/// The decimals of the currency whose code is exactly `code` in the crate's table (SPEC.md §4,
/// Functions): 2 for CHF, 0 for JPY, 3 for KWD; `None` for any other text: a code in lower case or
/// around spaces, a fund, a metal, a test code, `BTC`, the empty text. The currencies an order may
/// be priced in ([`Order::fiat`](crate::Order::fiat)), with the decimals its amount may have.
///
/// It needs no client, no key and no request: a shop asks it, for one, whether it may offer its
/// customers to pay in its currency, and in how many decimals its prices go to
/// [`Client::create_invoice`](crate::Client::create_invoice).
///
/// ```
/// use sattleme_checkout::currency_digits;
///
/// assert_eq!(currency_digits("CHF"), Some(2));
/// assert_eq!(currency_digits("JPY"), Some(0));
/// assert_eq!(currency_digits("chf"), None);
/// assert_eq!(currency_digits("XAU"), None);
/// ```
pub fn currency_digits(code: &str) -> Option<u32> {
    CURRENCY_DIGITS
        .binary_search_by(|(known, _)| (*known).cmp(code))
        .ok()
        .map(|index| CURRENCY_DIGITS[index].1)
}
